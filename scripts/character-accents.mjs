// Offline build-time extraction from the displayed first PNG frame.
// No image dependency or runtime decoding; source sprites are never modified.
import { readFile, writeFile } from "node:fs/promises";
import { inflateSync } from "node:zlib";
const root = new URL("../mods/spaces-status/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("icons/plushies/source.json", root), "utf8"));
function pixels(png, frameWidth, frameHeight) {
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20), depth = png[24], type = png[25];
  if (png[28] || ![3, 6].includes(type) || ![4, 8].includes(depth)) throw Error("Unsupported PNG");
  const chunks = []; let palette, alpha;
  for (let at = 8; at < png.length;) {
    const n = png.readUInt32BE(at), tag = png.toString("ascii", at + 4, at + 8), bytes = png.subarray(at + 8, at + 8 + n);
    if (tag === "IEND") break;
    if (tag === "IDAT") chunks.push(bytes);
    if (tag === "PLTE") palette = bytes;
    if (tag === "tRNS") alpha = bytes;
    at += n + 12;
  }
  const bits = depth * (type === 6 ? 4 : 1), stride = Math.ceil(width * bits / 8), bpp = Math.ceil(bits / 8);
  const raw = inflateSync(Buffer.concat(chunks)), rows = [], out = [];
  const paeth = (a, b, c) => {
    const p = a + b - c, x = Math.abs(p - a), y = Math.abs(p - b), z = Math.abs(p - c);
    return x <= y && x <= z ? a : y <= z ? b : c;
  };
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)], row = Buffer.alloc(stride), prev = rows[y - 1];
    for (let x = 0; x < stride; x++) {
      const a = row[x - bpp] ?? 0, b = prev?.[x] ?? 0, c = prev?.[x - bpp] ?? 0;
      row[x] = raw[y * (stride + 1) + x + 1] + [0, a, b, Math.floor((a + b) / 2), paeth(a, b, c)][filter];
    }
    rows.push(row);
    if (y >= frameHeight) continue;
    for (let x = 0; x < frameWidth; x++) {
      if (type === 6) out.push([...row.subarray(x * 4, x * 4 + 4)]);
      else {
        const index = depth === 8 ? row[x] : (row[x >> 1] >> (x % 2 ? 0 : 4)) & 15;
        out.push([...palette.subarray(index * 3, index * 3 + 3), alpha?.[index] ?? 255]);
      }
    }
  }
  return out;
}
function accent(pixels) {
  const candidates = pixels.filter(([r, g, b, a]) => a >= 128 && Math.max(r, g, b) > 50 && Math.min(r, g, b) < 230).map(([r, g, b, a]) => {
    const max = Math.max(r, g, b), min = Math.min(r, g, b), delta = max - min, s = max ? delta / max : 0;
    const h = delta === 0 ? 0 : ((max === r ? (g - b) / delta : max === g ? 2 + (b - r) / delta : 4 + (r - g) / delta) + 6) % 6;
    return { rgb: [r, g, b], hue: Math.round(h * 4) % 24, weight: (a / 255) * s ** 1.5 * Math.sqrt(max / 255), saturated: s >= .2 };
  });
  const chromatic = candidates.filter(p => p.saturated), source = chromatic.length >= 8 ? chromatic : candidates;
  if (!source.length) return "#8e98a8";
  const bins = Array.from({ length: 24 }, (_, i) => source.filter(p => Math.min((p.hue - i + 24) % 24, (i - p.hue + 24) % 24) <= 1).reduce((sum, p) => sum + (chromatic.length >= 8 ? p.weight : 1), 0));
  const hue = bins.indexOf(Math.max(...bins)), colors = new Map();
  for (const p of source) {
    if (Math.min((p.hue - hue + 24) % 24, (hue - p.hue + 24) % 24) > 1) continue;
    const hex = "#" + p.rgb.map(c => c.toString(16).padStart(2, "0")).join("");
    colors.set(hex, (colors.get(hex) ?? 0) + (chromatic.length >= 8 ? p.weight : 1));
  }
  const picked = [...colors].sort((a, b) => b[1] - a[1])[0][0];
  // Lift very dark sprite accents for UI frames, preserving the sampled hue.
  const rgb = [1, 3, 5].map(i => parseInt(picked.slice(i, i + 2), 16)), scale = Math.max(1, 140 / Math.max(...rgb));
  return "#" + rgb.map(c => Math.round(c * scale).toString(16).padStart(2, "0")).join("");
}
const entries = [];
for (const sprite of manifest.records.flatMap(record => record.sprites)) {
  const png = await readFile(new URL(`icons/plushies/${sprite.id}.png`, root));
  entries.push([sprite.id, accent(pixels(png, sprite.frameWidth, sprite.frameHeight))]);
}
await writeFile(new URL("character-accents.ts", root), "// Generated by npm run character-accents from first-frame sprite pixels.\n"
  + 'import type { Color } from "gpui-kit";\n'
  + 'import type { PlushId } from "./plush-catalog.js";\n'
  + `export const CHARACTER_ACCENTS: Record<PlushId, Color> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`);
console.log(`Extracted ${entries.length} character accents.`);
