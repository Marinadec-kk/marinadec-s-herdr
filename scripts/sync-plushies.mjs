// Development-only import. Keep original PNGs/metadata and per-asset licenses.
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const commit = "0d1b13963500df557e5f092c0094b9da83b30ac9";
const base = `https://raw.githubusercontent.com/space-wizards/space-station-14/${commit}/Resources/Textures/Objects/Fun/Plushies`;
const root = new URL("../mods/spaces-status/", import.meta.url);
const output = new URL("icons/plushies/", root);
const groups = ["arachnid", "atmosian", "bee", "carp", "diona", "expi", "hampter", "human", "lamp", "lizard", "moth", "narsie", "nukie", "penguin", "ratvar", "rouny", "shark", "sheep", "slime", "snake", "vox", "xeno"];
const licenses = {
  "CC-BY-SA-3.0": "https://creativecommons.org/licenses/by-sa/3.0/",
  "CC-BY-SA-4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
  "CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
};
const bytes = async url => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return Buffer.from(await response.arrayBuffer());
};
const digest = data => createHash("sha256").update(data).digest("hex");
await mkdir(output, { recursive: true });
const records = await Promise.all(groups.map(async group => {
  const metaBytes = await bytes(`${base}/${group}.rsi/meta.json`);
  const meta = JSON.parse(metaBytes);
  if (!licenses[meta.license]) throw new Error(`Refusing unsupported license ${meta.license}: ${group}`);
  await writeFile(new URL(`${group}.meta.json`, output), metaBytes);
  const sprites = await Promise.all(meta.states.filter(state => !/inhand|equipped/i.test(state.name)).map(async state => {
    const id = `ss14-${group}-${state.name}`;
    const png = await bytes(`${base}/${group}.rsi/${state.name}.png`);
    if (!png.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) throw new Error(`Not a PNG: ${id}`);
    const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
    await writeFile(new URL(`${id}.png`, output), png);
    return {
      id, label: state.name === "icon" ? group : `${group} · ${state.name}`,
      width, height, frameWidth: meta.size.x, frameHeight: meta.size.y,
      license: meta.license, sha256: digest(png),
      source: `${base}/${group}.rsi/${state.name}.png`,
    };
  }));
  return { group, copyright: meta.copyright, license: meta.license, sprites };
}));
records.sort((a, b) => a.group.localeCompare(b.group));
const sprites = records.flatMap(record => record.sprites);
await writeFile(new URL("plush-catalog.ts", root),
  "// Generated by npm run sync-plushies; do not edit.\n"
  + `export const PLUSHIES = ${JSON.stringify(sprites)} as const;\n`
  + "export type PlushId = typeof PLUSHIES[number]['id'];\n");
await writeFile(new URL("source.json", output), JSON.stringify({ repository: "space-wizards/space-station-14", commit, records }, null, 2) + "\n");
const credits = [
  "# Space Station 14 plush sprites", "",
  `Source: https://github.com/space-wizards/space-station-14/tree/${commit}/Resources/Textures/Objects/Fun/Plushies`, "",
  "PNGs are copied unchanged. The UI displays the first 32×32 frame of sheets; it does not animate them.",
  "The licenses below apply to these assets, not the repository's MIT code license.",
  "Original per-directory metadata is included alongside the PNGs.",
  "The non-commercial vulp.rsi set is deliberately excluded.", "",
  ...records.flatMap(record => [
    `## ${record.group}`, "",
    record.copyright, "",
    `License: [${record.license}](${licenses[record.license]}).`, "",
    ...record.sprites.map(sprite => `- [${sprite.id}.png](${sprite.source})`), "",
  ]),
];
await writeFile(new URL("CREDITS.md", output), credits.join("\n").trimEnd() + "\n");
console.log(`Imported ${sprites.length} SS14 plush avatars with attribution. No NC assets imported.`);

const fontCommit = "8dc5b4fcbbf3303402a6f3b587976c73cf4e212e";
const fontBase = `https://raw.githubusercontent.com/google/fonts/${fontCommit}/ofl/tiny5`;
const font = await bytes(`${fontBase}/Tiny5%5BBLED,JITT,ROND,wdth,wght%5D.ttf`);
const ofl = await bytes(`${fontBase}/OFL.txt`);
await mkdir(new URL("fonts/", root), { recursive: true });
await writeFile(new URL("fonts/Tiny5.ttf", root), font);
await writeFile(new URL("fonts/OFL-Tiny5.txt", root), ofl.toString("utf8").replace(/[ \t]+$/gm, ""));
await writeFile(new URL("fonts/tiny5-source.json", root),
  JSON.stringify({ repository: "google/fonts", path: "ofl/tiny5", commit: fontCommit, sha256: digest(font), license: "OFL-1.1", family: "Tiny5" }, null, 2) + "\n");
console.log("Imported Tiny5 (Latin/Cyrillic), with OFL license.");
