// Development-only asset import. The installed mod never downloads icons.
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const commit = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7";
const upstream = `https://raw.githubusercontent.com/google/material-design-icons/${commit}`;
const root = new URL("../mods/spaces-status/", import.meta.url);
const families = [
  ["MaterialIcons-Regular", "ttf"], ["MaterialIconsOutlined-Regular", "otf"],
  ["MaterialIconsRound-Regular", "otf"], ["MaterialIconsSharp-Regular", "otf"],
  ["MaterialIconsTwoTone-Regular", "otf"],
];
const fetchBytes = async url => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return Buffer.from(await response.arrayBuffer());
};
await mkdir(new URL("fonts/", root), { recursive: true });
const manifest = { repository: "google/material-design-icons", commit, files: {} };
const sets = await Promise.all(families.map(async ([name, extension]) => {
  const [font, index] = await Promise.all([
    fetchBytes(`${upstream}/font/${name}.${extension}`),
    fetchBytes(`${upstream}/font/${name}.codepoints`),
  ]);
  await writeFile(new URL(`fonts/${name}.${extension}`, root), font);
  manifest.files[`${name}.${extension}`] = createHash("sha256").update(font).digest("hex");
  manifest.files[`${name}.codepoints`] = createHash("sha256").update(index).digest("hex");
  return new Map(index.toString("utf8").trim().split(/\r?\n/).map(line => {
    const [icon, hex] = line.trim().split(/\s+/);
    return [icon, Number.parseInt(hex, 16)];
  }));
}));
const metadataResponse = await fetchBytes("https://fonts.google.com/metadata/icons");
manifest.metadata = {
  url: "https://fonts.google.com/metadata/icons",
  sha256: createHash("sha256").update(metadataResponse).digest("hex"),
};
const metadata = JSON.parse(metadataResponse.toString("utf8").replace(/^\)\]\}'\s*/, ""));
const byName = new Map(metadata.icons.map(icon => [icon.name, icon]));
const names = [...new Set(sets.flatMap(set => [...set.keys()]))].sort();
const icons = names.map(name => {
  const info = byName.get(name);
  return {
    name, codes: sets.map(set => set.get(name) ?? null),
    categories: info?.categories ?? ["other"],
    search: [name.replaceAll("_", " "), ...(info?.tags ?? [])].join(" ").toLowerCase(),
  };
});
const source = `// Generated by npm run sync-icons; do not edit. Upstream ${commit}.\n`
  + "export interface MaterialIcon { name: string; codes: (number | null)[]; categories: string[]; search: string }\n"
  + `export const MATERIAL_ICONS: readonly MaterialIcon[] = ${JSON.stringify(icons)};\n`;
await writeFile(new URL("material-catalog.ts", root), source);
const license = await fetchBytes(`${upstream}/LICENSE`);
await writeFile(new URL("fonts/LICENSE", root), license);
manifest.files.LICENSE = createHash("sha256").update(license).digest("hex");
manifest.files = Object.fromEntries(Object.entries(manifest.files).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
await writeFile(new URL("fonts/source.json", root), JSON.stringify(manifest, null, 2) + "\n");
console.log(`Imported ${icons.length} icon names, ${sets.map(set => set.size).join("/")} glyphs per family.`);
console.log(`Fonts and source manifest: ${fileURLToPath(new URL("fonts/", root))}`);
